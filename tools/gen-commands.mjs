#!/usr/bin/env node
// tools/gen-commands.mjs -- writes CHESS_COMMANDS.md from the app itself:
// every function as LISTCOMMANDS(1) describes it (app/chess/described.ts),
// asked through Commands.chess as a control-bus request asks it, and the
// old ADDRESS CHESS lines from script.ts's table, so the reference cannot
// drift from the functions; its examples are rexx/reference-examples.rexx,
// which spec_app_chess_rexx runs.
//
//   node --no-warnings tools/gen-commands.mjs           rewrite CHESS_COMMANDS.md
//   node --no-warnings tools/gen-commands.mjs --check   exit 1 if it differs
//
// Runs the TypeScript model on node's type stripping (node 22.6 and later).
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const OUT = path.join(ROOT, "CHESS_COMMANDS.md");
const { Commands } = await import(path.join(ROOT, "app/chess/commands.ts"));
const { OLD } = await import(path.join(ROOT, "app/chess/script.ts"));

const unstem = (s) => Array.from({ length: Number(s[0]) }, (_, i) => s[i + 1]);
const answer = await new Commands().chess("LISTCOMMANDS(1)", () => {});
if (!answer.ok) throw new Error(`LISTCOMMANDS(1): ${answer.message}`);
const fns = unstem(answer.output).map((d) => ({ ...d, params: unstem(d.params) }));

// A cell of a Markdown table: pipes escaped, new lines as spaces.
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");

const out = [];
const say = (...lines) => out.push(...lines);

say("# Chess: the REXX functions and ADDRESS CHESS", "",
  "<!-- Generated by tools/gen-commands.mjs from app/chess/described.ts (LISTCOMMANDS(1)) and app/chess/script.ts: edit those, then",
  "     run `node --no-warnings tools/gen-commands.mjs`. run-tests.sh's `commands-doc` entry fails when this file differs. -->", "",
  "Every action on the game is a command (`app/chess/commands.ts`), and each has a REXX function (`app/chess/control.ts`).",
  "A script in the app, any REXX program on the machine (over sae's control bus) and an AI client (through the MCP server)",
  "all call the same functions. The old app's `ADDRESS CHESS` lines (`move from=e2 to=e4`) work as they did.", "",
  "## Quick start", "",
  "```rexx",
  "/* In the app, or from outside: REQUIRE \"./chess-address.js\" first (rexx/README.md) */",
  "ADDRESS CHESS",
  "'MOVE(\"e2\", \"e4\")'            /* RESULT is the move in SAN: e4 */",
  "\"move from=c7 to=c5\"           /* an old line, as before */",
  "'GETBOARD()'",
  "SAY RESULT",
  "```", "",
  "In a script inside the app the functions are called directly too: `r = MOVESAN(\"Nf3\")`, `SAY GETFEN()`.", "");

say("## The functions", "",
  `${fns.length} of them, as \`LISTCOMMANDS(1)\` gives them. Optional parameters are in brackets. A function that cannot do what it is asked`,
  "(an illegal move, a square that is none, a FEN that is wrong) fails with the reason, which a script sees as its error and",
  "the bus and the MCP server give back.", "",
  "| Function | Does | Gives |", "|---|---|---|");
for (const f of fns) say(`| [\`${cell(f.signature)}\`](#${f.name.toLowerCase()}) | ${cell(f.does)} | ${cell(f.gives)} |`);
say("");
for (const f of fns) {
  say(`### ${f.name}`, "", "```rexx", f.signature, "```", "", `${f.does}. Gives ${f.gives}.`, "");
  if (f.params.length) {
    say("| Parameter | Kind | |", "|---|---|---|");
    for (const p of f.params) say(`| \`${p.name}\` | ${p.type}${p.optional ? ", optional" : ""}${p.variadic ? ", any number" : ""} | ${cell(p.about)} |`);
    say("");
  }
}

say("## The kinds of parameter", "",
  "| Kind | What it is |", "|---|---|",
  "| square | a square, `\"e4\"` |",
  "| san | a move in standard algebraic notation, `\"Nf3\"`, `\"O-O\"`, `\"exd5\"`, `\"e8=Q\"` (coordinate notation, `\"e2e4\"`, too) |",
  "| fen | a position in FEN |",
  "| piece | a promotion piece: queen, rook, bishop or knight (or q, r, b, n) |",
  "| side | white or black (for the computer player: white, black, both or none) |",
  "| level | the computer player's level, 1 to 4 |",
  "| text, number, flag, json, stem | text; a number; 1 or 0; JSON as text; a REXX stem (`list.0` how many, `list.1`, ...) |", "");

say("## The old ADDRESS CHESS lines", "",
  "The old app's twelve commands, each now a function. A line's RESULT is what the function gives, as JSON text where the old",
  "gave JSON. A line of the app's own commands works too: `ADDRESS CHESS \"game.move san=Nf3\"`.", "",
  "| Line | Is now |", "|---|---|");
const params = { "move": " from=e2 to=e4", "set-ai-difficulty": " level=3" };
for (const [line, o] of Object.entries(OLD)) say(`| \`${line}${params[line] ?? ""}\` | \`${o.fn}()\`${o.json ? ", as JSON" : ""} |`);
say("",
  "### RC, RESULT and ERRORTEXT", "",
  "In a script in the app: RC is 0 when the line worked, 1 when it was refused (ERRORTEXT and RESULT say why), and 2 for a",
  "command there is none of. The old app numbered its refusals (10-19 for `move`, 21-29 for `get-board`, ... 121-129 for",
  "`get-game-info`); they are 1 now, each with its reason. From another program over the bus (`rexx/chess-address.js`),",
  "RC is 1 for any refusal and 2 when there is no app to ask.", "",
  "```rexx",
  "ADDRESS CHESS \"move from=e2 to=e5\"",
  "IF RC <> 0 THEN SAY \"refused:\" ERRORTEXT     /* e2 to e5 is not a legal move for white */",
  "```", "");

say("## Undo", "",
  "`UNDO()` takes back a step: one move made on its own, or every move one script, one control-bus request or one MCP call",
  "made, together. `REDO()` makes a step again. A request or a call that fails part way is taken back whole, and its error",
  "ends \"(nothing it did was kept)\".", "");

say("## From another program: the control bus", "",
  "Started with `--control-bus` (`../sae/target/build/bin/sae --app app --control-bus`), the app answers requests from this",
  "machine on sae's sealed control bus (sae's `docs/control-bus.md`). A request is one REXX expression, worked out as",
  "`LET RESULT = <request>`:", "",
  "```bash",
  "../sae/target/sae-bus Chess 'MOVE(\"e2\", \"e4\")'",
  "../sae/target/sae-bus Chess 'MOVESAN(\"e5\"); MOVESAN(\"Nf3\")'     # one step of undo",
  "../sae/target/sae-bus Chess 'CHESSCOMMAND(\"get-status\")'         # an old line",
  "```", "",
  "From REXX, `REQUIRE \"./chess-address.js\"` and `ADDRESS CHESS` ([rexx/README.md](rexx/README.md)). sae stops a request",
  "whose work runs past 5 s at a stretch, and answers for one still running at 10 s; the app takes either back whole.", "");

say("## From an AI client: the MCP server", "",
  "`mcp/chess-mcp.js` ([mcp/README.md](mcp/README.md)) offers `chess_move`, `chess_board`, `chess_call` (any function above",
  "by name, its arguments checked against `LISTCOMMANDS(1)` before anything is sent), `chess_run_program` (a whole REXX",
  "program, one step of undo) and `chess_list_commands`; `--tools=rexx` or `all` add `chess_run`, one REXX command.", "",
  "```bash",
  "claude mcp add chess -- node /path/to/chaess/mcp/chess-mcp.js",
  "```", "");

say("## Examples", "",
  "`rexx/reference-examples.rexx`, as it is; `spec_app_chess_rexx` runs it against the app. Inside the app, drop the",
  "`REQUIRE` line. RexxJS wants `IF ... THEN` and its statement on one line",
  "([asks/rexxjs-if-then-next-line.md](asks/rexxjs-if-then-next-line.md)).", "",
  "```rexx", ...fs.readFileSync(path.join(ROOT, "rexx/reference-examples.rexx"), "utf8").trimEnd().split("\n"), "```", "");

const text = out.join("\n");
if (process.argv.includes("--check")) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (now !== text) {
    console.error("gen-commands: CHESS_COMMANDS.md differs from LISTCOMMANDS(1): run node --no-warnings tools/gen-commands.mjs");
    process.exit(1);
  }
  console.log(`gen-commands: CHESS_COMMANDS.md matches LISTCOMMANDS(1) (${fns.length} functions)`);
} else {
  fs.writeFileSync(OUT, text);
  console.log(`gen-commands: wrote CHESS_COMMANDS.md (${fns.length} functions)`);
}
